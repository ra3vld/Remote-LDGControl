#!/usr/bin/env python3
"""Generate LVGL 8 DejaVu Sans subsets for the LCD (requires Pillow)."""
import argparse
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]

def generate(font_path):
    out = ['// Generated by scripts/generate_display_fonts.py; see docs/licenses/DejaVu.txt.',
           '#include "display_fonts.h"', '#ifdef WITH_DISPLAY']
    for size in (10, 14, 24, 32):
        font = ImageFont.truetype(str(font_path), size)
        points = list(range(32, 127)) + list(range(0x400, 0x460)) if size <= 14 else sorted(set(map(ord, ' -./0123456789:W')))
        bitmap, glyphs = [], ['    {0,0,0,0,0,0},']
        for point in points:
            char = chr(point)
            left, top, right, bottom = font.getbbox(char, anchor='ls')
            width, height = right-left, bottom-top
            image = Image.new('L', (width, height))
            ImageDraw.Draw(image).text((-left, -top), char, font=font, fill=255, anchor='ls')
            pixels = [(pixel+8)//17 for pixel in image.getdata()]
            if len(pixels) % 2:
                pixels.append(0)
            offset = len(bitmap)
            bitmap.extend(pixels[i]*16+pixels[i+1] for i in range(0, len(pixels), 2))
            glyphs.append(f'    {{{offset},{round(font.getlength(char)*16)},{width},{height},{left},{-bottom}}},')
        ascent, descent = font.getmetrics()
        out += [f'namespace font{size} {{', 'static const uint8_t bitmap[] = {']
        out += ['    '+','.join(f'0x{b:02x}' for b in bitmap[i:i+24])+',' for i in range(0,len(bitmap),24)]
        out += ['};', 'static const lv_font_fmt_txt_glyph_dsc_t glyphs[] = {', *glyphs, '};',
                'static const uint16_t unicode[] = {'+','.join(str(p-32) for p in points)+'};',
                'static const lv_font_fmt_txt_cmap_t maps[] = {',
                f'    {{32,{points[-1]-31},1,unicode,nullptr,{len(points)},LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}}', '};',
                'static lv_font_fmt_txt_glyph_cache_t cache;',
                'static const lv_font_fmt_txt_dsc_t descriptor = {',
                '    .glyph_bitmap=bitmap, .glyph_dsc=glyphs, .cmaps=maps, .kern_dsc=nullptr,',
                '    .kern_scale=0, .cmap_num=1, .bpp=4, .kern_classes=0, .bitmap_format=0, .cache=&cache', '};', '}',
                f'extern const lv_font_t ldg_font_{size} = {{',
                '    .get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt, .get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,',
                f'    .line_height={ascent+descent}, .base_line={descent}, .subpx=LV_FONT_SUBPX_NONE,',
                f'    .underline_position=-1, .underline_thickness=1, .dsc=&font{size}::descriptor', '};']
    return '\n'.join(out+['#endif', ''])

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--font', type=Path, default=Path('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf'))
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    dest = ROOT/'src/display_fonts.cpp'
    result = generate(args.font)
    if args.check:
        if not dest.exists() or dest.read_text() != result:
            raise SystemExit('display_fonts.cpp is stale')
    else:
        dest.write_text(result)
