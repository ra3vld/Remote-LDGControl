#!/usr/bin/env python3
"""Regenerate/check the ESP-IDF 5.5.5 compact bundle (LE offset-table format)."""
from pathlib import Path
import argparse,struct
from cryptography import x509
from cryptography.hazmat.primitives import serialization

def build_bundle(paths):
    certificates=[x509.load_der_x509_certificate(path.read_bytes()) for path in paths]
    if not certificates:raise ValueError('At least one trusted root is required')
    certificates.sort(key=lambda cert:cert.subject.public_bytes())
    records=[]
    for cert in certificates:
        subject=cert.subject.public_bytes()
        key=cert.public_key().public_bytes(serialization.Encoding.DER,serialization.PublicFormat.SubjectPublicKeyInfo)
        records.append(struct.pack('<HH',len(subject),len(key))+subject+key)
    offset=4*len(records);offsets=[]
    for record in records:
        offsets.append(offset);offset+=len(record)
    return struct.pack('<'+'I'*len(offsets),*offsets)+b''.join(records)

header='''/* ISRG Root X1/X2, generated by scripts/build_mqtt_ca.py from certs/mqtt.
 * ESP-IDF 5.5.5 little-endian offset-table format.
 * Compact default bundle for verified MQTT TLS; preserves the existing OTA map.
 * Certificate public data is distributed under Mozilla Public License 2.0.
 */
.section .rodata.mqtt_ca_bundle,"a"
.balign 4
.global _binary_x509_crt_bundle_start
.global _binary_x509_crt_bundle_end
_binary_x509_crt_bundle_start:
'''
def assembly(bundle):
    return header+''.join('.byte '+','.join(str(v) for v in bundle[i:i+16])+'\n' for i in range(0,len(bundle),16))+'_binary_x509_crt_bundle_end:\n'

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    root=Path(__file__).resolve().parents[1]
    result=assembly(build_bundle(sorted((root/'certs/mqtt').glob('*.der'))))
    dest=root/'src/mqtt_ca_bundle.S'
    if args.check:
        if dest.read_text()!=result:raise SystemExit('MQTT CA bundle is stale; run scripts/build_mqtt_ca.py')
    else:dest.write_text(result)
